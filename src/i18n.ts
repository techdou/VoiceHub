export type I18nKey = keyof typeof dict.zh;

/** 测试用：暴露字典本体。 */
export { dict };

const state = reactive({ locale: "zh" as Locale });

export function setLocale(locale: Locale) {
  state.locale = locale;
}

export function resolveLocale(language: string, systemLocale: string): Locale {
  if (language === "zh_cn") return "zh";
  if (language === "english") return "en";
  return systemLocale.startsWith("zh") ? "zh" : "en";
}

export function useI18n() {
  // 直接返回函数（读取响应式 state），模板与 computed 中均可调用。
  const t = (key: I18nKey): string => {
    const table = dict[state.locale] as Record<string, string>;
    return table[key] ?? (dict.zh as Record<string, string>)[key] ?? key;
  };
  return { t, locale: computed(() => state.locale) };
}

export function formatDuration(ms: number): string {
  if (ms < 1000) return `${ms}ms`;
  const seconds = ms / 1000;
  if (seconds < 60) return `${seconds.toFixed(1)}s`;
  const minutes = Math.floor(seconds / 60);
  const rest = Math.round(seconds % 60);
  return `${minutes}m ${rest}s`;
}
